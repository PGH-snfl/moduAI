-- Make user_profiles the single onboarding source of truth, persist legal
-- consent evidence, and provide an administrator-readable authentication log.

create table if not exists public.user_consents (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  document_type text not null check (document_type in ('terms', 'privacy')),
  document_version text not null,
  acceptance_method text not null check (acceptance_method in ('email_signup', 'social_onboarding')),
  provider text not null check (provider in ('email', 'google', 'kakao', 'other')),
  accepted_at timestamp with time zone not null default timezone('utc'::text, now()),
  unique (user_id, document_type, document_version)
);

create index if not exists user_consents_user_accepted_idx
  on public.user_consents (user_id, accepted_at desc);

alter table public.user_consents enable row level security;

drop policy if exists "Users can read own consents" on public.user_consents;
create policy "Users can read own consents"
  on public.user_consents for select
  using (auth.uid() = user_id);

drop policy if exists "Admins can read all consents" on public.user_consents;
create policy "Admins can read all consents"
  on public.user_consents for select
  using (auth.jwt()->'app_metadata'->>'role' = 'admin');

create table if not exists public.auth_audit_events (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  event_type text not null check (event_type in (
    'sign_in', 'sign_out', 'signup_completed', 'password_changed', 'identity_linked'
  )),
  provider text not null default 'email' check (provider in ('email', 'google', 'kakao', 'other')),
  success boolean not null default true,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamp with time zone not null default timezone('utc'::text, now())
);

create index if not exists auth_audit_events_user_created_idx
  on public.auth_audit_events (user_id, created_at desc);
create index if not exists auth_audit_events_created_idx
  on public.auth_audit_events (created_at desc);

alter table public.auth_audit_events enable row level security;

drop policy if exists "Admins can read auth audit events" on public.auth_audit_events;
create policy "Admins can read auth audit events"
  on public.auth_audit_events for select
  using (auth.jwt()->'app_metadata'->>'role' = 'admin');

create or replace function public.record_auth_audit_event(
  p_event_type text,
  p_provider text default null,
  p_metadata jsonb default '{}'::jsonb
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
  v_provider text;
  v_metadata jsonb;
begin
  if v_user_id is null then
    raise exception 'Authentication required';
  end if;
  if p_event_type not in ('sign_in', 'sign_out', 'signup_completed', 'password_changed', 'identity_linked') then
    raise exception 'Unsupported auth audit event';
  end if;

  v_provider := lower(coalesce(nullif(p_provider, ''), auth.jwt()->'app_metadata'->>'provider', 'email'));
  if v_provider not in ('email', 'google', 'kakao') then v_provider := 'other'; end if;

  -- Never retain credentials or tokens supplied accidentally by a caller.
  v_metadata := coalesce(p_metadata, '{}'::jsonb)
    - 'email' - 'password' - 'token' - 'access_token' - 'refresh_token' - 'nonce';
  if pg_column_size(v_metadata) > 4096 then v_metadata := '{}'::jsonb; end if;

  -- Auth callbacks and React effects can fire twice; collapse immediate duplicates.
  if exists (
    select 1 from public.auth_audit_events
    where user_id = v_user_id
      and event_type = p_event_type
      and provider = v_provider
      and created_at > timezone('utc'::text, now()) - interval '5 seconds'
  ) then return; end if;

  insert into public.auth_audit_events (user_id, event_type, provider, metadata)
  values (v_user_id, p_event_type, v_provider, v_metadata);
end;
$$;

revoke all on function public.record_auth_audit_event(text, text, jsonb) from public, anon;
grant execute on function public.record_auth_audit_event(text, text, jsonb) to authenticated;

create or replace function public.complete_social_onboarding(
  p_display_name text,
  p_avatar_url text,
  p_terms_version text,
  p_privacy_version text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
  v_provider text;
begin
  if v_user_id is null then raise exception 'Authentication required'; end if;
  if not exists (select 1 from auth.users where id = v_user_id and email is not null) then
    raise exception 'A verified provider email is required';
  end if;
  if length(trim(coalesce(p_display_name, ''))) < 1 or length(trim(p_display_name)) > 40 then
    raise exception 'Display name must be between 1 and 40 characters';
  end if;
  if length(trim(coalesce(p_terms_version, ''))) < 1 or length(trim(coalesce(p_privacy_version, ''))) < 1 then
    raise exception 'Consent versions are required';
  end if;

  v_provider := lower(coalesce(auth.jwt()->'app_metadata'->>'provider', 'other'));
  if v_provider not in ('google', 'kakao', 'email') then v_provider := 'other'; end if;

  insert into public.user_profiles (
    id, display_name, avatar_url, onboarding_completed, signup_provider, updated_at
  ) values (
    v_user_id, trim(p_display_name), nullif(trim(coalesce(p_avatar_url, '')), ''), true, v_provider, timezone('utc'::text, now())
  ) on conflict (id) do update set
    display_name = excluded.display_name,
    avatar_url = coalesce(excluded.avatar_url, public.user_profiles.avatar_url),
    onboarding_completed = true,
    updated_at = excluded.updated_at;

  insert into public.user_consents (user_id, document_type, document_version, acceptance_method, provider)
  values
    (v_user_id, 'terms', trim(p_terms_version), 'social_onboarding', v_provider),
    (v_user_id, 'privacy', trim(p_privacy_version), 'social_onboarding', v_provider)
  on conflict (user_id, document_type, document_version) do nothing;

  perform public.record_auth_audit_event('signup_completed', v_provider, jsonb_build_object('method', 'social_onboarding'));
end;
$$;

revoke all on function public.complete_social_onboarding(text, text, text, text) from public, anon;
grant execute on function public.complete_social_onboarding(text, text, text, text) to authenticated;

-- Email signup is complete only when the signup form supplied explicit consent.
create or replace function public.handle_new_user_profile()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_email_signup_complete boolean :=
    coalesce((new.raw_user_meta_data ->> 'onboarding_completed')::boolean, false)
    and coalesce((new.raw_user_meta_data ->> 'terms_accepted')::boolean, false)
    and coalesce((new.raw_user_meta_data ->> 'privacy_accepted')::boolean, false);
begin
  if v_email_signup_complete then
    insert into public.user_profiles (id, display_name, avatar_url, onboarding_completed, signup_provider)
    values (
      new.id,
      coalesce(new.raw_user_meta_data ->> 'full_name', split_part(coalesce(new.email, '사용자'), '@', 1)),
      coalesce(new.raw_user_meta_data ->> 'avatar_url', new.raw_user_meta_data ->> 'picture'),
      true,
      'email'
    ) on conflict (id) do update set
      onboarding_completed = true,
      updated_at = timezone('utc'::text, now());

    insert into public.user_consents (user_id, document_type, document_version, acceptance_method, provider)
    values
      (new.id, 'terms', coalesce(nullif(new.raw_user_meta_data ->> 'terms_version', ''), 'unknown'), 'email_signup', 'email'),
      (new.id, 'privacy', coalesce(nullif(new.raw_user_meta_data ->> 'privacy_version', ''), 'unknown'), 'email_signup', 'email')
    on conflict (user_id, document_type, document_version) do nothing;
  end if;
  return new;
end;
$$;
